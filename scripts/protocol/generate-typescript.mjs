#!/usr/bin/env node
/** Generate TypeScript protocol types from schemas/protocol/v1.json */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const schema = JSON.parse(
  readFileSync(join(root, "schemas/protocol/v1.json"), "utf8"),
);
const outPath = join(
  root,
  "apps/browser-service/src/generated/protocol-v1.ts",
);
mkdirSync(dirname(outPath), { recursive: true });

const methodUnion = Object.values(schema.methodCatalog)
  .flat()
  .map((method) => `"${method}"`)
  .join(" | ");

const contents = `// GENERATED by scripts/protocol/generate-typescript.mjs — do not edit.
/** Retcon local protocol v1 wire types. */

export const PROTOCOL_VERSION = 1 as const;

export type TransportKind = "named_pipe" | "unix_socket";

export interface Discovery {
  transport: TransportKind;
  path: string;
  token: string;
  pid: number;
  version: string;
  protocolVersion: typeof PROTOCOL_VERSION;
}

export interface AuthLine {
  auth: string;
}

export interface ClientHello {
  kind: "client.hello";
  protocolVersion: typeof PROTOCOL_VERSION;
  clientVersion: string;
  features: string[];
}

export interface ServerHello {
  kind: "server.hello";
  protocolVersion: typeof PROTOCOL_VERSION;
  serverVersion: string;
  features: string[];
}

export type RpcMethod = ${methodUnion};

export interface RpcRequest {
  id: number;
  method: RpcMethod | (string & {});
  params: Record<string, unknown>;
}

export interface RpcError {
  id: string;
  code: string;
  source: string;
  user_message: string;
  technical_message: string;
  suggested_fix?: string | null;
  retryable: boolean;
  diagnostic?: unknown;
}

export interface RpcResponse {
  id: number;
  result?: Record<string, unknown>;
  error?: RpcError;
}

export interface RpcEvent {
  event: Record<string, unknown>;
}

export interface CancelFrame {
  kind: "request.cancel";
  id: number;
}

export interface PingFrame {
  kind: "ping";
}

export interface PongFrame {
  kind: "pong";
}

export type ClientFrame =
  | RpcRequest
  | CancelFrame
  | PingFrame;

export type ServerFrame = RpcResponse | RpcEvent | ServerHello | PongFrame;
`;

writeFileSync(outPath, contents);
console.log(`wrote ${outPath}`);
