import sharp from "sharp";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const brandDir = join(root, "public", "assets", "brand");
const socialDir = join(root, "public", "assets", "social");
await mkdir(socialDir, { recursive: true });

const mark = await readFile(join(brandDir, "retcon-mark.svg"));
const iconPipeline = sharp(mark);
await Promise.all(
  [64, 192, 512, 1024].map((size) =>
    iconPipeline
      .clone()
      .resize(size, size)
      .png()
      .toFile(join(brandDir, `retcon-icon-${size}.png`)),
  ),
);

